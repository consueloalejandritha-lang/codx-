import assert from 'node:assert/strict';
import { loadModule } from './load_source.mjs';
const { attachScenePlayback } = await loadModule('src/components/scenePlayback.ts');
const listeners = new Map();
let intersection;
let preference;
let disconnected = false;
const reduced = { matches: false, addEventListener: (_, fn) => { preference = fn; }, removeEventListener: () => { preference = undefined; } };
globalThis.window = { matchMedia: () => reduced };
globalThis.document = { hidden: false, addEventListener: (name, fn) => listeners.set(name, fn), removeEventListener: name => listeners.delete(name) };
globalThis.IntersectionObserver = class { constructor(fn) { intersection = fn; } observe() {} disconnect() { disconnected = true; } };
let playing = false;
let plays = 0;
let reject = false;
let blocked = false;
let resolvePending;
const video = {
  play() { plays++; if (resolvePending === null) return new Promise(resolve => { resolvePending = resolve; }); if (reject) return Promise.reject(new Error('Autoplay blocked')); playing = true; return Promise.resolve(); },
  pause() { playing = false; },
};
const tick = async () => { await Promise.resolve(); await Promise.resolve(); };
const controller = attachScenePlayback(video, value => { blocked = value; });
assert.equal(plays, 0, 'No offscreen autoplay');
intersection([{ isIntersecting: true }]); await tick();
assert.equal(playing, true);
intersection([{ isIntersecting: false }]);
assert.equal(playing, false);
document.hidden = true;
intersection([{ isIntersecting: true }]);
assert.equal(playing, false);
document.hidden = false; listeners.get('visibilitychange')(); await tick();
assert.equal(playing, true);
reduced.matches = true; preference();
assert.equal(playing, false);
assert.equal(blocked, true, 'Reduced motion offers manual play');
controller.play(); await tick();
assert.equal(playing, true);
assert.equal(blocked, false);
reject = true; intersection([{ isIntersecting: true }]); await tick();
assert.equal(blocked, true);
reject = false; controller.play(); await tick();
assert.equal(blocked, false, 'Manual retry recovers autoplay failure');
resolvePending = null; controller.play();
intersection([{ isIntersecting: false }]);
playing = true; resolvePending(); await tick();
assert.equal(playing, false, 'Late play resolution cannot resume an offscreen video');
controller.dispose();
assert.equal(disconnected, true);
assert.equal(listeners.size, 0);
assert.equal(preference, undefined);
assert.equal(playing, false);
console.log('PASS: scene videos defer, pause offscreen/background, respect reduced motion, retry and clean up.');
